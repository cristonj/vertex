const r1 = (n) => Math.round(n * 10) / 10;

/**
 * Lay out a string as stroke glyph paths. Local coords: baseline at y=0, starts at x=0.
 * @returns {{ parts: Array<{d: string}>, width: number, scale: number }}
 */
export function textPath(str, size = 16, { spacing = 2, align = 'left' } = {}) {
  const s = size / 6;
  const adv = (4 + spacing) * s;
  const parts = [];
  const w = textWidth(str, size, { spacing });
  let x0 = align === 'center' ? -w / 2 : align === 'right' ? -w : 0;
  for (const ch of String(str).toUpperCase()) {
    const glyph = FONT[ch];
    if (glyph) {
      for (const line of glyph) {
        let d = `M${r1(x0 + line[0][0] * s)} ${r1((line[0][1] - 6) * s)}`;
        for (let i = 1; i < line.length; i++) d += `L${r1(x0 + line[i][0] * s)} ${r1((line[i][1] - 6) * s)}`;
        parts.push({ d });
      }
    }
    x0 += adv;
  }
  return { parts, width: w, scale: s };
}

/**
 * A complete text shape (horizontally centered on the origin, baseline at y=0).
 * Drop it straight into shapes: defineShape('title', textShape('GAME OVER', 32, {stroke:'#fff'}))
 */
export function textShape(str, size = 16, style = {}) {
  const { parts } = textPath(str, size, { align: style.align ?? 'center' });
  delete (style = { ...style }).align;
  return {
    parts: parts.map((p) => ({ ...p, fill: 'none', stroke: '#fff', width: 1.5, ...style })),
  };
}

/** Width of a laid-out string, for centering/alignment. */
export function textWidth(str, size = 16, { spacing = 2 } = {}) {
  return (String(str).length * (4 + spacing) - spacing) * (size / 6);
}
